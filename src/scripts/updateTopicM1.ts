async function updateTopicM1() {
  console.log('🚀 Обновление темы m1 (Прямолинейное движение) в Supabase...\n')

  try {
    // 1. Создаем/проверяем раздел "mechanics"
    console.log('📚 Проверка раздела "mechanics"...')
    const sectionMechanics = {
      id: 'mechanics',
      title: 'Механика',
      description: 'Движение, силы, энергия, импульс',
      icon_name: 'Gauge',
      color: 'from-blue-500 to-cyan-500',
      total_topics: 22,
      order_index: 1
    }

    const { error: sectionError } = await supabase
      .from('sections')
      .upsert(sectionMechanics, { onConflict: 'id' })

    if (sectionError) {
      console.error('❌ Ошибка создания раздела:', sectionError.message)
      process.exit(1)
    }
    console.log('✅ Раздел "mechanics" готов')

    // 2. Создаем/проверяем подраздел "kinematics"
    console.log('\n📖 Проверка подраздела "kinematics"...')
    const subsectionKinematics = {
      id: 'kinematics',
      title: 'Кинематика',
      section_id: 'mechanics',
      order_index: 1
    }

    const { error: subsectionError } = await supabase
      .from('subsections')
      .upsert(subsectionKinematics, { onConflict: 'id' })

    if (subsectionError) {
      console.error('❌ Ошибка создания подраздела:', subsectionError.message)
      process.exit(1)
    }
    console.log('✅ Подраздел "kinematics" готов')

    // 3. Обновляем тему m1
    console.log('\n📝 Обновление темы m1...')
    const { data, error } = await supabase
      .from('topics')
      .upsert(topicM1, { onConflict: 'id' })

    if (error) {
      console.error('❌ Ошибка обновления темы:', error.message)
      console.error('Детали:', error)
      process.exit(1)
    }

    console.log('✅ Тема m1 успешно обновлена в Supabase!')
    console.log('\n📋 Обновленные данные:')
    console.log(`   ID: ${topicM1.id}`)
    console.log(`   Название: ${topicM1.title}`)
    console.log(`   Описание: ${topicM1.description}`)
    console.log(`   Формул: ${topicM1.formulas.length}`)
    console.log(`   Примеров: ${topicM1.examples.length}`)
    console.log(`   Задач: ${topicM1.problems.length}`)
    console.log(`   Длина теории: ${topicM1.theory.length} символов`)

  } catch (error: any) {
    console.error('❌ Критическая ошибка:', error.message)
    process.exit(1)
  }
}

